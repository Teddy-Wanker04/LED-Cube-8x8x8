void initOLED()
{
  Wire.begin(OLED_SDA, OLED_SCL);

  display.begin(OLED_ADDRESS, true);

  display.clearDisplay();
  display.setTextSize(1);
  display.setTextColor(SH110X_WHITE);
  display.display();
}

void showLogoIntro()
{
  display.clearDisplay();

  display.setTextSize(1);
  display.setTextColor(SH110X_WHITE);

  display.setCursor(128 / 2, 5);
  display.println("Design");

  display.setCursor(128 / 2, 15);
  display.println("& Build by");

  display.setCursor(128 / 2, 30);
  display.println("Teddy");

  display.setCursor(100, 50);
  display.println("2026");

  display.drawBitmap(
    0,
    0,
    image_data,
    128,
    64,
    SH110X_WHITE
  );

  display.display();
  delay(5000);

  display.clearDisplay();
  display.display();
}